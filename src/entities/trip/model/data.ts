export type TripGroup = 'travel' | 'race'

export interface ItineraryDay {
  label: string
  title: string
  text: string
}

export interface TripItinerary {
  title: string
  intro: string
  days: ItineraryDay[]
  note: string
}

export interface TripPoint {
  ll: [number, number]
  caption?: string
}

export interface TripPhoto {
  src: string
  alt: string
  caption?: string
}

export interface TripRoute {
  name: string
  duration: string
  extent: string
  legend: string[]
  mapCaption: string
  mapImage?: string
  mapImageAlt?: string
  mapPoints: TripPoint[]
  mapClosed?: boolean
  itinerary: TripItinerary
}

export interface Departure {
  id: string
  dates: string
  route: TripRoute
}

export interface TripHarbor {
  port: string
  coords: string
  season: string
  crew: string
  note: string
}

export interface Trip {
  id: string
  group: TripGroup
  geo: string
  year: string
  price: string
  priceUnit: string
  priceNote?: string
  tagline: string
  cover: string
  coverAlt: string
  photos: TripPhoto[]
  video?: { href: string; label: string }
  included?: string[]
  reviewIds: string[]
  harbor: TripHarbor
  departures: Departure[]
}

